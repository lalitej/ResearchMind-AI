import streamlit as st
from research_tools.ui import apply_theme, page_header, provider_picker
from research_tools.history_store import init_db, log_event
from research_tools.ai_features import generate_research_output

st.set_page_config(page_title="Advanced Analysis | ResearchMind AI", page_icon="🔬", layout="wide")
init_db(); apply_theme()
page_header("Research intelligence", "Advanced paper analysis", "Go beyond the abstract: inspect methods, evidence, limitations and research opportunities.")
paper = st.session_state.get("paper_data")
paper_id = st.session_state.get("paper_record_id")
if not paper:
    st.info("Open Research Workspace and import a paper first. Your active paper will be available here.")
    st.stop()
provider = provider_picker("analysis_provider")
analysis_key = f"rm_latest_analysis_{paper_id or 'active'}"
metadata = paper.get("metadata") or {}
st.markdown(f"**Active paper:** {metadata.get('title', 'Untitled research paper')}")
analysis_type = st.selectbox("Analysis depth", ["Comprehensive analysis", "Methodology and experimental design", "Research gaps and future directions", "Strengths, limitations and critical appraisal"])
if st.button("Generate analysis", type="primary", use_container_width=True):
    task = "Analyze the supplied paper. Structure the response with: 1) research problem and objectives, 2) key contributions, 3) methodology and study design, 4) datasets/materials and evaluation, 5) principal findings with exact reported values, 6) strengths, 7) limitations, 8) research gaps, 9) future work. Mark anything not stated in the paper."
    if analysis_type != "Comprehensive analysis": task = f"Focus the analysis on {analysis_type.lower()}. Include evidence and page references where available; distinguish explicit author statements from your critical interpretation."
    try:
        with st.spinner("Analyzing the paper with the selected AI provider..."):
            result = generate_research_output([paper], task, provider, max_output_tokens=5000)
        st.session_state[analysis_key] = result["text"]
        st.session_state[analysis_key + "_provider"] = result.get("provider", provider)
        if paper_id: log_event("analysis", "Advanced analysis generated", analysis_type, result["text"], paper_id)
    except Exception as exc: st.error(f"Analysis failed: {exc}")
if st.session_state.get(analysis_key):
    st.caption(f"Generated by {st.session_state.get(analysis_key + '_provider', provider)}")
    st.markdown(st.session_state[analysis_key])
    from research_tools.exports import make_docx, make_pdf
    c1,c2=st.columns(2)
    with c1:
        try: st.download_button("Download DOCX", make_docx("ResearchMind AI — Advanced Analysis", st.session_state[analysis_key]), "research_analysis.docx", mime="application/vnd.openxmlformats-officedocument.wordprocessingml.document", use_container_width=True)
        except ImportError: st.caption("Install python-docx to enable DOCX export.")
    with c2:
        try: st.download_button("Download PDF", make_pdf("ResearchMind AI — Advanced Analysis", st.session_state[analysis_key]), "research_analysis.pdf", mime="application/pdf", use_container_width=True)
        except ImportError: st.caption("Install reportlab to enable PDF export.")
